"""Writes lib/core/content/adhkar_quran.dart: the Quran passages of the
morning and evening adhkar, taken from the bundled Quran data so that the
text, the transliteration and the translations match the reader."""
import json

def surah(n):
    return json.load(open(f'assets/quran/s/{n:03d}.json', encoding='utf-8'))

def fix(text):
    # A slip in the source transliteration of 2:255.
    return text.replace(' mww ', ' maa ').replace(' мвв ', ' ма ')

def q(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"

kursi = {k: fix(surah(2)[k][254]) for k in ('ar', 'ru', 'en', 'tl', 'tc')}
quls = {k: [] for k in ('ar', 'ru', 'en', 'tl', 'tc')}
for n in (112, 113, 114):
    data = surah(n)
    for k in quls:
        # One ayah to a line, as in the reader; the Arabic keeps the
        # end-of-ayah sign instead.
        quls[k].append((' ۝ ' if k == 'ar' else '\n').join(data[k]))

out = [
    '// Generated by tool/build_adhkar.py from assets/quran. Do not edit.',
    '',
]
for name, part in (('ayatAlKursi', kursi), ('threeQuls', {k: '\n\n'.join(v) for k, v in quls.items()})):
    for field, key in (('Arabic', 'ar'), ('Latin', 'tl'), ('Cyrillic', 'tc'), ('English', 'en'), ('Russian', 'ru')):
        text = part[key]
        text = text.replace('\n', '\\n')
        out.append(f'const {name}{field} =\n    {q(text)};'.replace("\\\\n", "\\n"))
    out.append('')
open('lib/core/content/adhkar_quran.dart', 'w', encoding='utf-8').write('\n'.join(out))
